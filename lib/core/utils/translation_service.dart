import 'package:shared_preferences/shared_preferences.dart';

enum AppLanguage { en, ar }

class TranslationNotifier extends StateNotifier<AppLanguage> {
  TranslationNotifier() : super(AppLanguage.en) {
    _loadLanguage();
  }

  static const String _langKey = 'dealspot_lang';

  Future<void> _loadLanguage() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString(_langKey);
    if (saved == 'ar') {
      state = AppLanguage.ar;
    } else {
      state = AppLanguage.en;
    }
  }

  Future<void> setLanguage(AppLanguage lang) async {
    state = lang;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_langKey, lang.name);
  }

  void toggleLanguage() {
    setLanguage(state == AppLanguage.en ? AppLanguage.ar : AppLanguage.en);
  }

  String translateField(Map<String, dynamic>? obj, String fieldName) {
    if (obj == null) return '';
    final key = '${fieldName}_${state.name}';
    if (obj.containsKey(key)) {
      return obj[key]?.toString() ?? obj['${fieldName}_en']?.toString() ?? '';
    }
    return obj[fieldName]?.toString() ?? '';
  }

  bool get isRtl => state == AppLanguage.ar;
  TextDirection get direction => isRtl ? TextDirection.rtl : TextDirection.ltr;
}

final translationProvider = StateNotifierProvider<TranslationNotifier, AppLanguage>((ref) {
  return TranslationNotifier();
});

